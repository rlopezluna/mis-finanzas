"""Genera el atajo "Gasto" de Mis finanzas (plist XML sin firmar).

Uso: python3 generar_atajo.py Gasto.xml

Versión sin preguntas de importación (en iOS 27 el botón "Agregar atajo" se quedaba
atorado con ellas). La primera vez que se corre pide la llave (propone lo que esté
en el portapapeles) y la guarda en iCloud Drive/Atajos/mis-finanzas-llave.txt; las
siguientes veces la lee de ahí. Si el servidor responde que la llave no sirve, borra el
archivo para que la próxima vez la vuelva a pedir. Valida con el validador de Shortcuts Playground.
"""
import plistlib, uuid, sys
U = lambda: str(uuid.uuid4()).upper()
BASE = 'https://qgbwrdunmdywekdquyxi.supabase.co/rest/v1/rpc/'
APIKEY = 'sb_publishable_BoSRUuFaVH-DOeIsuuwTgA_x87NbyLT'
ARCHIVO = 'mis-finanzas-llave.txt'
OBJ = '￼'

def tstr(s): return {'Value': {'string': s}, 'WFSerializationType': 'WFTextTokenString'}
def ref_out(uid, name, coerce=None):
    r = {'OutputName': name, 'OutputUUID': uid, 'Type': 'ActionOutput'}
    if coerce: r['Aggrandizements'] = [{'CoercionItemClass': coerce, 'Type': 'WFCoercionVariableAggrandizement'}]
    return r
def ref_var(name): return {'Type': 'Variable', 'VariableName': name}
def tok(ref): return {'Value': {'attachmentsByRange': {'{0, 1}': ref}, 'string': OBJ}, 'WFSerializationType': 'WFTextTokenString'}
def att(ref): return {'Value': ref, 'WFSerializationType': 'WFTextTokenAttachment'}
def field(key, value): return {'WFItemType': 0, 'WFKey': tstr(key), 'WFValue': value}
def dictval(items): return {'Value': {'WFDictionaryFieldValueItems': items}, 'WFSerializationType': 'WFDictionaryFieldValue'}
def act(ident, params): return {'WFWorkflowActionIdentifier': ident, 'WFWorkflowActionParameters': params}
def com(t): return act('is.workflow.actions.comment', {'UUID': U(), 'WFCommentActionText': t})
def post(uid, name, rpc, items):
    return act('is.workflow.actions.downloadurl', {'UUID': uid, 'CustomOutputName': name, 'WFURL': BASE + rpc, 'WFHTTPMethod': 'POST',
        'ShowHeaders': True, 'WFHTTPHeaders': dictval([field('apikey', tstr(APIKEY))]), 'WFHTTPBodyType': 'JSON', 'WFJSONValues': dictval(items)})

uF, uG, uCB, uK, uR, uM, uMV, uA, uL, uC, uP, uMS, uN, uF2, uTX = (U() for _ in range(15))
grp = U()
grp2 = U()
LLAVE = ref_var('Llave')
actions = [
    com('Gasto: registra un gasto en Mis finanzas sin abrir la app. Pregunta el monto, la forma de pago (solo las que tienes activas) y en qué; lo guarda en tu cuenta y muestra una notificación.'),
    com('Shortcuts generated by Shortcuts Playground. La primera vez pide tu llave (Más > Cuenta > Atajo de iPhone en la app) y la guarda en iCloud Drive/Atajos/' + ARCHIVO + '. Para cambiarla, borra ese archivo. La llave solo sirve para agregar gastos; no deja ver tus datos.'),
    act('is.workflow.actions.documentpicker.open', {'UUID': uF, 'CustomOutputName': 'Archivo de llave', 'WFGetFilePath': ARCHIVO, 'WFFileErrorIfNotFound': False, 'WFShowFilePicker': False}),
    com('Llave guardada:\n- Si existe el archivo de llave, se usa su texto.\n- Si no, se pide (propone el portapapeles) y se guarda para la próxima vez.\n- En ambos casos queda en la variable Llave.'),
    act('is.workflow.actions.conditional', {'GroupingIdentifier': grp, 'WFControlFlowMode': 0, 'WFCondition': 100,
        'WFInput': {'Type': 'Variable', 'Variable': att(ref_out(uF, 'Archivo de llave'))}}),
    act('is.workflow.actions.gettext', {'UUID': uG, 'CustomOutputName': 'Llave guardada', 'WFTextActionText': tok(ref_out(uF, 'Archivo de llave', 'WFStringContentItem'))}),
    act('is.workflow.actions.setvariable', {'WFVariableName': 'Llave', 'WFInput': att(ref_out(uG, 'Llave guardada'))}),
    act('is.workflow.actions.conditional', {'GroupingIdentifier': grp, 'WFControlFlowMode': 1}),
    act('is.workflow.actions.getclipboard', {'UUID': uCB}),
    act('is.workflow.actions.ask', {'UUID': uK, 'CustomOutputName': 'Llave nueva', 'WFInputType': 'Text',
        'WFAskActionPrompt': 'Pega tu llave de Mis finanzas (empieza con mf_). Si ya la copiaste en la app, solo toca Listo.',
        'WFAskActionDefaultAnswer': tok(ref_out(uCB, 'Clipboard'))}),
    act('is.workflow.actions.setvariable', {'WFVariableName': 'Llave', 'WFInput': att(ref_out(uK, 'Llave nueva'))}),
    act('is.workflow.actions.setitemname', {'UUID': uR, 'WFInput': att(ref_out(uK, 'Llave nueva')), 'WFName': ARCHIVO}),
    act('is.workflow.actions.documentpicker.save', {'WFInput': att(ref_out(uR, 'Renamed Item')), 'WFAskWhereToSave': False, 'WFSaveFileOverwrite': True}),
    act('is.workflow.actions.conditional', {'GroupingIdentifier': grp, 'WFControlFlowMode': 2, 'UUID': U()}),
    post(uM, 'Respuesta métodos', 'metodos_atajo', [field('llave', tok(LLAVE))]),
    act('is.workflow.actions.getvalueforkey', {'UUID': uMV, 'CustomOutputName': 'Mis métodos', 'WFGetDictionaryValueType': 'Value', 'WFDictionaryKey': 'metodos', 'WFInput': att(ref_out(uM, 'Respuesta métodos'))}),
    act('is.workflow.actions.ask', {'UUID': uA, 'CustomOutputName': 'Monto', 'WFAskActionPrompt': '¿Cuánto gastaste?', 'WFInputType': 'Number'}),
    act('is.workflow.actions.choosefromlist', {'UUID': uL, 'CustomOutputName': 'Forma de pago', 'WFChooseFromListActionPrompt': '¿Con qué pagaste?', 'WFInput': att(ref_out(uMV, 'Mis métodos'))}),
    act('is.workflow.actions.ask', {'UUID': uC, 'CustomOutputName': 'Concepto', 'WFAskActionPrompt': '¿En qué? (opcional)', 'WFInputType': 'Text'}),
    com('Registrar: manda a Mis finanzas la llave, el monto, la forma de pago elegida y el concepto; luego muestra la respuesta.'),
    post(uP, 'Respuesta', 'atajo', [field('llave', tok(LLAVE)), field('monto', tok(ref_out(uA, 'Monto'))),
                                     field('metodo', tok(ref_out(uL, 'Forma de pago'))), field('concepto', tok(ref_out(uC, 'Concepto')))]),
    act('is.workflow.actions.getvalueforkey', {'UUID': uMS, 'CustomOutputName': 'Mensaje', 'WFGetDictionaryValueType': 'Value', 'WFDictionaryKey': 'mensaje', 'WFInput': att(ref_out(uP, 'Respuesta'))}),
    act('is.workflow.actions.gettext', {'UUID': uTX, 'CustomOutputName': 'Texto del mensaje', 'WFTextActionText': tok(ref_out(uMS, 'Mensaje'))}),
    com('Llave que ya no sirve:\n- Si la respuesta habla de la llave, se borra el archivo de llave.\n- Así la próxima vez el atajo vuelve a pedirla.'),
    act('is.workflow.actions.conditional', {'GroupingIdentifier': grp2, 'WFControlFlowMode': 0, 'WFCondition': 99, 'WFConditionalActionString': 'llave',
        'WFInput': {'Type': 'Variable', 'Variable': att(ref_out(uTX, 'Texto del mensaje'))}}),
    act('is.workflow.actions.documentpicker.open', {'UUID': uF2, 'CustomOutputName': 'Llave a borrar', 'WFGetFilePath': ARCHIVO, 'WFFileErrorIfNotFound': False, 'WFShowFilePicker': False}),
    act('is.workflow.actions.file.delete', {'WFInput': att(ref_out(uF2, 'Llave a borrar')), 'WFDeleteImmediatelyDelete': True}),
    act('is.workflow.actions.conditional', {'GroupingIdentifier': grp2, 'WFControlFlowMode': 2, 'UUID': U()}),
    act('is.workflow.actions.notification', {'UUID': uN, 'WFNotificationActionTitle': 'Mis finanzas', 'WFNotificationActionBody': tok(ref_out(uTX, 'Texto del mensaje'))}),
]
wf = {'WFWorkflowActions': actions, 'WFWorkflowClientVersion': '2700.0.4', 'WFWorkflowHasOutputFallback': False,
      'WFWorkflowIcon': {'WFWorkflowIconGlyphNumber': 59395, 'WFWorkflowIconStartColor': 4292093695},
      'WFWorkflowImportQuestions': [], 'WFWorkflowInputContentItemClasses': [], 'WFWorkflowMinimumClientVersion': 900,
      'WFWorkflowMinimumClientVersionString': '900', 'WFWorkflowName': 'Gasto', 'WFWorkflowOutputContentItemClasses': [], 'WFWorkflowTypes': []}
plistlib.dump(wf, open(sys.argv[1], 'wb'), fmt=plistlib.FMT_XML)
